def replace(u,t,old,new,ref,count=1):
    k=(u,t); actual=DOCS[k].count(old)
    if actual != count:
        raise ValueError(f'{u}/{t} {ref}: expected {count}, got {actual}: {old[:100]}')
    DOCS[k]=DOCS[k].replace(old,new)
    CHANGES.append(dict(unit=u,type=t,reference=ref,before=old,after=new,count=count))

def after(u,t,old,new,ref):
    replace(u,t,old,old+'\n\n'+new,ref)

def section(u,t,heading,new,ref):
    b=DOCS[u,t]; start=b.index(heading)
    assert start==0 or b[start-1]=='\n'
    level=len(heading)-len(heading.lstrip('#'))
    m=re.search(r'^#{1,'+str(level)+r'} ', b[start+len(heading):], re.M)
    end=start+len(heading)+m.start() if m else len(b)
    replace(u,t,b[start:end],new.strip()+'\n\n',ref)

def insert_heading(u,t,heading,content,ref):
    after(u,t,heading,content,ref)

def first_section(u,t,content,ref):
    m=re.search(r'^(?:## .+|\*\*一、.+\*\*)$',DOCS[u,t],re.M)
    assert m,(u,t)
    after(u,t,m.group(),content,ref)

