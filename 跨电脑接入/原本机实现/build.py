def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')

def dump(path, obj):
    write(path, json.dumps(obj, ensure_ascii=False, indent=2)+'\n')

def mdlink(label, p):
    return f'[{label}](<{p.as_posix()}>)'

